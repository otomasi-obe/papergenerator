def set_run_font(run, font_name=None, size_pt=None, bold=None, italic=None, color=None):
    if font_name:
        run.font.name = font_name
        rPr = run._element.get_or_add_rPr()
        rFonts = rPr.find(qn("w:rFonts"))
        if rFonts is None:
            rFonts = OxmlElement("w:rFonts")
            rPr.insert(0, rFonts)
        rFonts.set(qn("w:ascii"), font_name)
        rFonts.set(qn("w:hAnsi"), font_name)
        rFonts.set(qn("w:cs"), font_name)
    if size_pt:
        run.font.size = Pt(size_pt)
    if bold is not None:
        run.bold = bold
    if italic is not None:
        run.italic = italic
    if color:
        run.font.color.rgb = RGBColor(*color)


def set_para_spacing(para, before_pt=None, after_pt=None, line_tw=None):
    pf = para.paragraph_format
    if before_pt is not None:
        pf.space_before = Pt(before_pt)
    if after_pt is not None:
        pf.space_after = Pt(after_pt)
    if line_tw is not None:
        pPr = para._element.get_or_add_pPr()
        spacing = pPr.find(qn("w:spacing"))
        if spacing is None:
            spacing = OxmlElement("w:spacing")
            pPr.append(spacing)
        spacing.set(qn("w:line"), str(line_tw))
        spacing.set(qn("w:lineRule"), "auto")


def set_para_indent(para, first_line_tw=None, left_tw=None, hanging_tw=None):
    pPr = para._element.get_or_add_pPr()
    ind = pPr.find(qn("w:ind"))
    if ind is None:
        ind = OxmlElement("w:ind")
        pPr.append(ind)
    if first_line_tw is not None:
        ind.set(qn("w:firstLine"), str(first_line_tw))
    if left_tw is not None:
        ind.set(qn("w:left"), str(left_tw))
    if hanging_tw is not None:
        ind.set(qn("w:hanging"), str(hanging_tw))
        if ind.get(qn("w:firstLine")):
            del ind.attrib[qn("w:firstLine")]

def _detect_table_borders(doc):
    """Scan template for first body table and extract its border style.
    Returns a dict of {side: {val, sz, color}} compatible with set_table_borders."""
    body = doc._element.body
    body_tbl_found = False
    for child in body:
        if child.tag == qn("w:tbl"):
            # Skip first table (masthead) — no borders
            if not body_tbl_found:
                body_tbl_found = True
                continue
            # Second table = body table
            tblPr = child.find(qn("w:tblPr"))
            if tblPr is None:
                return None
            borders_elem = tblPr.find(qn("w:tblBorders"))
            if borders_elem is None:
                return None
            
            result = {}
            for side in ["top", "left", "bottom", "right", "insideH", "insideV"]:
                border = borders_elem.find(qn(f"w:{side}"))
                if border is not None:
                    result[side] = {
                        "val": border.get(qn("w:val"), "none"),
                        "sz": border.get(qn("w:sz"), "0"),
                        "color": border.get(qn("w:color"), "auto"),
                    }
                else:
                    result[side] = None  # Not set = inherit (none)
            
            # Also check cell-level borders on first row
            first_row = child.find(qn("w:tr"))
            if first_row is not None:
                first_cell = first_row.find(qn("w:tc"))
                if first_cell is not None:
                    tcPr = first_cell.find(qn("w:tcPr"))
                    if tcPr is not None:
                        cell_borders = tcPr.find(qn("w:tcBorders"))
                        if cell_borders is not None:
                            result["_cell"] = {}
                            for side in ["top", "left", "bottom", "right"]:
                                cb = cell_borders.find(qn(f"w:{side}"))
                                if cb is not None:
                                    result["_cell"][side] = {
                                        "val": cb.get(qn("w:val"), "none"),
                                        "sz": cb.get(qn("w:sz"), "0"),
                                    }
            return result
    return None


def set_table_borders(table, style_borders):
    """Apply border style to a table. style_borders can be:
    - dict: direct border definition from _detect_table_borders
    - str: legacy keyword ("full", "horizontal", "partial", "none")
    """
    from docx.oxml import OxmlElement
    tblPr = table._tbl.find(qn("w:tblPr"))
    if tblPr is None:
        tblPr = OxmlElement("w:tblPr")
        table._tbl.insert(0, tblPr)
    # Remove existing borders
    existing = tblPr.find(qn("w:tblBorders"))
    if existing is not None:
        tblPr.remove(existing)
    
    if isinstance(style_borders, dict):
        borders = OxmlElement("w:tblBorders")
        sides = ["top", "left", "bottom", "right", "insideH", "insideV"]
        for side in sides:
            el = OxmlElement(f"w:{side}")
            if side in style_borders and style_borders[side] is not None:
                b = style_borders[side]
                el.set(qn("w:val"), str(b.get("val", "none")))
                el.set(qn("w:sz"), str(b.get("sz", "0")))
                el.set(qn("w:space"), "0")
                el.set(qn("w:color"), str(b.get("color", "auto")))
            else:
                el.set(qn("w:val"), "none")
                el.set(qn("w:sz"), "0")
                el.set(qn("w:space"), "0")
                el.set(qn("w:color"), "auto")
            borders.append(el)
        tblPr.append(borders)
    elif isinstance(style_borders, str):
        style = style_borders
        borders = OxmlElement("w:tblBorders")
        for side in ("top", "left", "bottom", "right", "insideH", "insideV"):
            el = OxmlElement(f"w:{side}")
            if style == "horizontal":
                if side in ("top", "bottom", "insideH"):
                    el.set(qn("w:val"), "single")
                    el.set(qn("w:sz"), "4")
                    el.set(qn("w:space"), "0")
                    el.set(qn("w:color"), "000000")
                else:
                    el.set(qn("w:val"), "none")
                    el.set(qn("w:sz"), "0")
                    el.set(qn("w:space"), "0")
                    el.set(qn("w:color"), "auto")
            elif style == "full":
                el.set(qn("w:val"), "single")
                el.set(qn("w:sz"), "4")
                el.set(qn("w:space"), "0")
                el.set(qn("w:color"), "000000")
            elif style == "partial":
                if side in ("insideV", "left", "right"):
                    el.set(qn("w:val"), "none")
                    el.set(qn("w:sz"), "0")
                    el.set(qn("w:space"), "0")
                    el.set(qn("w:color"), "auto")
                else:
                    el.set(qn("w:val"), "single")
                    el.set(qn("w:sz"), "4")
                    el.set(qn("w:space"), "0")
                    el.set(qn("w:color"), "auto")
            else:  # none
                el.set(qn("w:val"), "none")
                el.set(qn("w:sz"), "0")
                el.set(qn("w:space"), "0")
                el.set(qn("w:color"), "auto")
            borders.append(el)
        tblPr.append(borders)
    
    # Apply cell-level borders if detected
    if isinstance(style_borders, dict) and "_cell" in style_borders:
        cell_cfg = style_borders["_cell"]
        for row in table.rows:
            for cell in row.cells:
                tcPr = cell._tc.find(qn("w:tcPr"))
                if tcPr is None:
                    tcPr = OxmlElement("w:tcPr")
                    cell._tc.insert(0, tcPr)
                existing_cb = tcPr.find(qn("w:tcBorders"))
                if existing_cb is not None:
                    tcPr.remove(existing_cb)
                if any(cell_cfg.get(s) for s in ["top", "bottom", "left", "right"]):
                    cell_borders = OxmlElement("w:tcBorders")
                    for side in ["top", "bottom", "left", "right"]:
                        el = OxmlElement(f"w:{side}")
                        if side in cell_cfg and cell_cfg[side] is not None:
                            cb = cell_cfg[side]
                            el.set(qn("w:val"), str(cb.get("val", "none")))
                            el.set(qn("w:sz"), str(cb.get("sz", "0")))
                            el.set(qn("w:space"), "0")
                            el.set(qn("w:color"), "auto")
                        else:
                            el.set(qn("w:val"), "none")
                            el.set(qn("w:sz"), "0")
                            el.set(qn("w:space"), "0")
                            el.set(qn("w:color"), "auto")
                        cell_borders.append(el)
                    tcPr.append(cell_borders)
    tblPr.append(borders)


def clear_body(doc):
    """Clear body text/tables but keep section break paragraphs and top image paragraphs/tables (logos)."""
    body = doc._element.body
    sectpr_paras = []
    logo_paras = []
    logo_tables = []

    # First pass: identify logo paragraphs (images in first 3 paragraphs)
    para_count = 0
    for child in body:
        if child.tag == qn("w:p"):
            para_count += 1
            if para_count <= 3:
                # Check if paragraph has image/drawing
                has_image = False
                for run in child.findall(qn("w:r")):
                    if run.findall(qn("w:drawing")):
                        has_image = True
                        break
                if has_image:
                    logo_paras.append(child)

    # Identify logo tables (tables with drawings in first 3 tables)
    table_count = 0
    for child in body:
        if child.tag == qn("w:tbl"):
            table_count += 1
            if table_count <= 3:
                # Check if table has drawing
                has_drawing = len(child.findall(f".//{qn('w:drawing')}")) > 0
                if has_drawing:
                    logo_tables.append(child)

    # Second pass: clear body but preserve logos and section breaks
    for child in list(body):
        if child.tag == qn("w:sectPr"):
            continue
        if child in logo_paras:
            continue  # Preserve logo paragraphs
        if child in logo_tables:
            continue  # Preserve logo tables
        if child.tag == qn("w:p"):
            pPr = child.find(qn("w:pPr"))
            if pPr is not None and pPr.find(qn("w:sectPr")) is not None:
                # Keep this paragraph (it has section break)
                # But clear its text content
                for run in child.findall(qn("w:r")):
                    child.remove(run)
                sectpr_paras.append(child)
                continue
        body.remove(child)
    return sectpr_paras


def distribute_section_breaks(doc, n_breaks):
    """Insert n_breaks section breaks evenly distributed among body paragraphs."""
    if n_breaks <= 0:
        return
    body = doc._element.body
    # Count content paragraphs (exclude final sectPr)
    content_elements = [c for c in body if c.tag != qn("w:sectPr")]
    total = len(content_elements)
    if total == 0:
        return
    # Calculate interval
    interval = max(1, total // (n_breaks + 1))
    # Insert section breaks at intervals (from end to start to preserve indices)
    insert_positions = []
    for i in range(1, n_breaks + 1):
        pos = min(i * interval, total - 1)
        if pos not in insert_positions:
            insert_positions.append(pos)
    # Get final sectPr to copy its properties
    final_sectpr = body.find(qn("w:sectPr"))
    for pos in reversed(insert_positions):
        target = content_elements[pos] if pos < len(content_elements) else content_elements[-1]
        # Add sectPr to this paragraph's pPr (inline section break)
        if target.tag == qn("w:p"):
            pPr = target.find(qn("w:pPr"))
            if pPr is None:
                pPr = OxmlElement("w:pPr")
                target.insert(0, pPr)
            sp = OxmlElement("w:sectPr")
            # Copy page size and margins from final sectPr
            if final_sectpr is not None:
                for prop_tag in ("w:pgSz", "w:pgMar", "w:cols"):
                    orig = final_sectpr.find(qn(prop_tag))
                    if orig is not None:
                        import copy
                        sp.append(copy.deepcopy(orig))
            pPr.append(sp)


def insert_column_break(doc, num_cols):
    """Insert continuous section break inline (attach to last paragraph, not empty para)."""
    if CFG["columns"] <= 1:
        return
    body = doc._element.body
    final_sectpr = body.find(qn("w:sectPr"))

    # Find last content paragraph (not empty, not already has sectPr)
    last_para = None
    for child in reversed(list(body)):
        if child.tag == qn("w:sectPr"):
            continue
        if child.tag == qn("w:p"):
            pPr = child.find(qn("w:pPr"))
            if pPr is not None and pPr.find(qn("w:sectPr")) is not None:
                continue
            last_para = child
            break

    if last_para is None:
        # No content paragraph found, skip
        return

    # Attach sectPr inline to last paragraph
    pPr = last_para.find(qn("w:pPr"))
    if pPr is None:
        pPr = OxmlElement("w:pPr")
        last_para.insert(0, pPr)

    sp = OxmlElement("w:sectPr")
    # Set type=continuous
    sec_type = OxmlElement("w:type")
    sec_type.set(qn("w:val"), "continuous")
    sp.append(sec_type)
    # Copy page size and margins from final sectPr
    if final_sectpr is not None:
        for prop_tag in ("w:pgSz", "w:pgMar"):
            orig = final_sectpr.find(qn(prop_tag))
            if orig is not None:
                import copy
                sp.append(copy.deepcopy(orig))
    # Set columns
    cols_el = OxmlElement("w:cols")
    cols_el.set(qn("w:num"), str(num_cols))
    sp.append(cols_el)
    pPr.append(sp)
def remove_trailing_empty_sectpr_paras(doc):
    """Remove empty paragraphs with sectPr at the end of body by moving sectPr to previous content paragraph."""
    body = doc._element.body
    to_process = []

    # Scan backwards from end to find trailing empty sectPr paragraphs
    for child in reversed(list(body)):
        if child.tag == qn("w:sectPr"):
            # Skip final sectPr, continue scanning
            continue
        if child.tag == qn("w:p"):
            pPr = child.find(qn("w:pPr"))
            if pPr is not None and pPr.find(qn("w:sectPr")) is not None:
                # This paragraph has a section break
                # Check if it's empty (no runs with text)
                has_content = False
                for run in child.findall(qn("w:r")):
                    t_elem = run.find(qn("w:t"))
                    if t_elem is not None and t_elem.text and t_elem.text.strip():
                        has_content = True
                        break

                if not has_content:
                    # Empty paragraph with sectPr - mark for processing
                    to_process.append(child)
                else:
                    # Non-empty paragraph - stop scanning
                    break
            else:
                # Paragraph without sectPr - stop scanning
                break
        elif child.tag == qn("w:tbl"):
            # Table - stop scanning (content found)
            break

    # Process each trailing empty sectPr paragraph
    removed_count = 0
    for empty_para in to_process:
        # Extract the sectPr from this empty paragraph
        pPr = empty_para.find(qn("w:pPr"))
        sectPr = pPr.find(qn("w:sectPr")) if pPr is not None else None

        if sectPr is not None:
            # Find the last content paragraph before this empty one
            empty_index = list(body).index(empty_para)
            target_para = None

            for i in range(empty_index - 1, -1, -1):
                child = list(body)[i]
                if child.tag == qn("w:p"):
                    # Check if this paragraph has content or is also empty
                    has_content = False
                    for run in child.findall(qn("w:r")):
                        t_elem = run.find(qn("w:t"))
                        if t_elem is not None and t_elem.text and t_elem.text.strip():
                            has_content = True
                            break
                    if has_content:
                        target_para = child
                        break
                elif child.tag == qn("w:tbl"):
                    # Can't attach sectPr to table, skip this one
                    break

            if target_para is not None:
                # Move sectPr to target paragraph
                target_pPr = target_para.find(qn("w:pPr"))
                if target_pPr is None:
                    target_pPr = OxmlElement("w:pPr")
                    target_para.insert(0, target_pPr)

                # Remove sectPr from empty paragraph and add to target
                pPr.remove(sectPr)
                target_pPr.append(sectPr)

                # Now remove the empty paragraph
                body.remove(empty_para)
                removed_count += 1

    return removed_count


def _remove_trailing_empty_sectpr_paras(doc):
    """Hapus paragraf kosong bersectPr (incl. zero-width) di ekor body."""
    body = doc._element.body
    to_remove = []
    for child in reversed(list(body)):
        if child.tag == qn("w:sectPr"):
            continue
        if child.tag != qn("w:p"):
            break
        pPr = child.find(qn("w:pPr"))
        if pPr is None or pPr.find(qn("w:sectPr")) is None:
            break
        txt = "".join(t.text or "" for t in child.findall(f".//{qn('w:t')}")).strip()
        if not txt or all(c == '\u200B' for c in txt):
            to_remove.append(child)
        else:
            break
    for child in to_remove:
        body.remove(child)


