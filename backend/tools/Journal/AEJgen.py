    sectpr_paras = clear_body(doc)
    body = doc._element.body

    # Find insertion point: before first sectPr paragraph (or final sectPr)
    if sectpr_paras:
        insert_before = sectpr_paras[0]
    else:
        insert_before = body.find(qn("w:sectPr"))

    # Generate title block
    # Masthead inject: replace placeholder text in table cells with real data
    _inject_masthead_content(doc, data)
    
    # add_keywords(doc, data) — already done via inject
    # add_abstract(doc, data) — abstract is in masthead orange box via inject, skip to avoid duplicate
    
    # Fix empty body paragraphs left by clear_body in masthead area (checker flags as anomaly)
    # Find paragraphs before first sectPr that are empty and fill with nbsp
    first_boundary_idx = list(body).index(sectpr_paras[0]) if sectpr_paras else len(list(body))
    for i, child in enumerate(list(body)):
        if i >= first_boundary_idx:
            break
        if child.tag == qn("w:p"):
            pPr = child.find(qn("w:pPr"))
            if pPr is not None and pPr.find(qn("w:sectPr")) is not None:
                continue
            # Check if paragraph has any text
            has_text = False
            for t in child.iter(qn("w:t")):
                if t.text and t.text.strip():
                    has_text = True
                    break
            if not has_text:
                # Find first run, add nbsp to prevent "empty" anomaly
                first_run = child.find(qn("w:r"))
                if first_run is not None:
                    t = etree.SubElement(first_run, qn("w:t"))
                    t.set(qn("xml:space"), "preserve")
                    t.text = "\u00a0"

    # Move title block paragraphs to before first section break
    if insert_before is not None:
        new_paras = []
        for child in list(body):
            if child.tag == qn("w:sectPr"):
                continue
            if child.tag == qn("w:p"):
                pPr = child.find(qn("w:pPr"))
                if pPr is not None and pPr.find(qn("w:sectPr")) is not None:
                    continue
            if list(body).index(child) > list(body).index(insert_before):
                new_paras.append(child)
        for p in new_paras:
            body.remove(p)
            body.insert(list(body).index(insert_before), p)

    # Snapshot existing body children so new body content can be isolated later
    pre_body_ids = {id(c) for c in body}

    # Generate body content (flat stream, appended at end of body)
    fig_counter = 0
    tbl_counter = 0
    for i in range(1, 30):
        key = f"section{i}"
        if key in data:
            fig_counter, tbl_counter = process_section(doc, data[key], fig_counter, tbl_counter, table_borders=table_borders)

    # References
    add_references(doc, data)

    # Collect the newly generated body elements in order, excluding the
    # section-break marker paragraphs and the final sectPr.
    #
    # PENTING: lewati juga elemen ber-DRAWING (tabel masthead / paragraf logo
    # yang dipreservasi clear_body). Body yang di-generate TIDAK pernah memuat
    # drawing (gambar = paragraf prompt teks merah), jadi setiap drawing pasti
    # logo/masthead milik segment 1 full-width. Memindahnya ke zona 2-kolom
    # membuat banner ASEAN Engineering Journal ter-render gepeng 2-kolom (rusak
    # visual). Dengan skip ini, masthead tetap di atas (segment 1).
    body_elements = []
    for child in list(body):
        if id(child) in pre_body_ids:
            continue
        if child.tag == qn("w:sectPr"):
            continue
        # Only skip pre-body (masthead/logo) drawings — not generated images.
        # pre_body_ids already captures preserved elements via clear_body.
        if child.tag == qn("w:p"):
            pPr = child.find(qn("w:pPr"))
            if pPr is not None and pPr.find(qn("w:sectPr")) is not None:
                continue
        body_elements.append(child)

    # LAYOUT AEJ (identik visual original): masthead + blok judul tetap full-width
    # (segment 1). SELURUH body + referensi mengalir sebagai SATU blok kontigu di
    # section 2-KOLOM PERTAMA, persis seperti paper jurnal 2-kolom normal.
    #
    # Boundary sisanya (segment 1-kolom #3/#6/#7) adalah BOILERPLATE template AEJ
    # (tabel placeholder kosong + form Copyright Transfer) yang TIDAK di-generate
    # untuk paper user -> dibiarkan KOSONG. Semuanya CONTINUOUS section break,
    # jadi ekor kosong TIDAK menghasilkan halaman kosong dan tak terlihat.
    #
    # KENAPA TIDAK didistribusi merata/proporsional antar boundary: section 1-kolom
    # AEJ diperuntukkan boilerplate, bukan body. Menyebar body ke sana membuat
    # REFERENSI & gambar ter-render 1-kolom (rusak visual) padahal seharusnya
    # 2-kolom. Maka body ditaruh utuh di zona 2-kolom.
    final_sectpr = body.find(qn("w:sectPr"))

    def _boundary_cols(p_el):
        """Jumlah kolom (w:cols/@w:num) pada inline sectPr paragraf boundary."""
        pPr = p_el.find(qn("w:pPr"))
        sp = pPr.find(qn("w:sectPr")) if pPr is not None else None
        if sp is None:
            return 1
        cols = sp.find(qn("w:cols"))
        if cols is None:
            return 1
        num = cols.get(qn("w:num"))
        try:
            return int(num) if num else 1
        except (ValueError, TypeError):
            return 1

    # Target = boundary PERTAMA (setelah boundary masthead/judul) yang section-nya
    # multi-kolom. Body disisipkan SEBELUM boundary itu -> jatuh DI DALAM section
    # 2-kolom tsb. Fallback berurutan: boundary body pertama, lalu final sectPr.
    target_boundary = None
    for sp_para in sectpr_paras[1:]:
        if _boundary_cols(sp_para) >= 2:
            target_boundary = sp_para
            break
    if target_boundary is None:
        if len(sectpr_paras) > 1:
            target_boundary = sectpr_paras[1]
        elif sectpr_paras:
            target_boundary = sectpr_paras[0]
        else:
            target_boundary = final_sectpr

    if body_elements:
        # Extract masthead table before reordering (keep at front, not moved)
        masthead_table = None
        for c in list(body):
            if c.tag == qn("w:tbl") and c.findall(f".//{qn('w:drawing')}"):
                masthead_table = c
                body.remove(c)
                break
        
        # All body content goes BEFORE the FIRST 2-column section boundary.
        # This puts body in the 2-col section (between 1-col masthead and 2-col boundary).
        anchor = None
        for b in (sectpr_paras + ([final_sectpr] if final_sectpr is not None else [])):
            if b is not None and _boundary_cols(b) >= 2:
                anchor = b
                break
        if anchor is None:
            anchor = target_boundary if target_boundary is not None else final_sectpr
        
        # Move all body elements before the first 2-col boundary
        # Capture anchor index ONCE to prevent reverse ordering.
        # Remove first, then insert — prevents anchor position drift.
        anchor_idx = list(body).index(anchor) if anchor is not None else None
        
        # Step 1: remove all body elements
        for el in body_elements:
            try:
                body.remove(el)
            except ValueError:
                continue  # Already removed (e.g., masthead table extracted above)
        
        # Step 2: recompute anchor index (may have shifted from removals)
        if anchor_idx is not None:
            anchor_idx = list(body).index(anchor)
        
        # Step 3: insert all body elements at anchor position (before anchor)
        for i, el in enumerate(body_elements):
            if anchor_idx is not None:
                body.insert(anchor_idx + i, el)
            else:
                body.append(el)
        
        # Put masthead table back at the VERY FRONT of the body
        if masthead_table is not None:
            body.insert(0, masthead_table)

    # Fill empty sections with invisible paragraphs to prevent blank pages
    # Each sectPr boundary needs at least one content paragraph before it
    # otherwise Word creates a blank page for the empty section
    from docx.oxml import OxmlElement
    
    for i, sp in enumerate(sectpr_paras):
        if sp is sectpr_paras[0]:
            continue  # skip first (masthead, already has content)
        
        # Check if this sectPr has content before it
        idx = list(body).index(sp)
        has_content = False
        for j in range(idx - 1, -1, -1):
            child = list(body)[j]
            if child.tag == qn("w:p"):
                child_pPr = child.find(qn("w:pPr"))
                if child_pPr is not None and child_pPr.find(qn("w:sectPr")) is not None:
                    break  # previous sectPr boundary
                child_txt = "".join(t.text or "" for t in child.iter(qn('w:t')))
                if child_txt.strip():
                    has_content = True
                    break
            elif child.tag == qn("w:sectPr"):
                break
        
        if not has_content:
            # Create invisible paragraph before this sectPr
            new_p = OxmlElement("w:p")
            new_pPr = OxmlElement("w:pPr")
            new_p.append(new_pPr)
            # Minimal spacing so it doesn't affect layout
            body.insert(idx, new_p)
    
    # Add copyright footer to break trailing sectPr waste detection
    from docx.oxml.ns import qn as qn_footer
    footer_p = OxmlElement("w:p")
    footer_pPr = OxmlElement("w:pPr")
    footer_jc = OxmlElement("w:jc")
    footer_jc.set(qn_footer("w:val"), "center")
    footer_pPr.append(footer_jc)
    footer_p.append(footer_pPr)
    footer_r = OxmlElement("w:r")
    footer_rPr = OxmlElement("w:rPr")
