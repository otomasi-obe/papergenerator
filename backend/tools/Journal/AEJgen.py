def add_figure(doc, fig_data, fig_counter):
    fig_no = str(fig_data.get("ImageNumber", fig_counter)).strip()
    title = str(fig_data.get("Title", "")).strip()
    if not title:
        title = str(fig_data.get("caption", f"Figure {fig_no}")).strip()
    prompt_hint = str(fig_data.get("Prompt", "")).strip()
    image_path = fig_data.get("Path") or fig_data.get("path") or ""
    if not title or title.strip().lower() in {f"figure {fig_no}".lower(), f"fig. {fig_no}".lower()}:
        # ponytail: JSON sometimes has image paths but empty captions; use filename as minimal non-bold caption description.
        # Upgrade path: require captions in frontend upload metadata.
        base = os.path.splitext(os.path.basename(str(image_path)))[0].replace("_", " ").replace("-", " ").title()
        title = f"Figure {fig_no}. {base}" if base else f"Figure {fig_no}. Image"
    image_url = fig_data.get("image_url", fig_data.get("url", ""))
    if not image_url:
        image_url = os.environ.get("PAPER_IMAGE_URL", "")
    
    # Attempt to embed actual image
    image_embedded = False
    import os as _os
    
    # Resolve full image path: check relative to JSON file location first
    img_full_path = ""
    if image_path:
        # Strip URL prefix if present
        if image_path.startswith("http"):
            image_url = image_path
            image_path = ""
        else:
            # Normalise: AI tokenizer sometimes inserts spaces inside filenames
            # (e.g. "flowchart_t uning.jpg" → "flowchart_tuning.jpg")
            image_path_norm = image_path.replace(" ", "")
            
            # Priority 0: absolute path — check directly
            if _os.path.isabs(image_path) and _os.path.isfile(image_path):
                img_full_path = image_path
            elif _os.path.isabs(image_path_norm) and _os.path.isfile(image_path_norm):
                img_full_path = image_path_norm
            
            # Try relative paths if absolute not found
            if not img_full_path:
                # Try relative to TEMPLATE_JSON directory's parent/<paper_id>/image/
                json_dir = _os.path.dirname(_os.path.abspath(str(TEMPLATE_JSON))) if TEMPLATE_JSON else ""
                # Build search candidates: original + normalised
                candidates = []
                if image_path_norm != image_path:
                    candidates.append(image_path_norm)  # direct normalised path
                candidates.extend([
                    _os.path.join(json_dir, image_path),
                    _os.path.join(json_dir, image_path_norm) if image_path_norm != image_path else "",
                    _os.path.join(_os.path.dirname(json_dir), "image", image_path) if json_dir else "",
                    _os.path.join(_os.path.dirname(json_dir), "image", image_path_norm) if json_dir and image_path_norm != image_path else "",
                    _os.path.join(str(_os.path.dirname(_os.path.abspath(__file__))), image_path),
                    _os.path.join(str(_os.path.dirname(_os.path.abspath(__file__))), image_path_norm) if image_path_norm != image_path else "",
                ])
                for p in candidates:
                    if p and _os.path.isfile(p):
                        img_full_path = p
                        break
            
            # 5. Look for image in user/*/<paper_id>/image/ (legacy) AND user/<paper_id>/image/ (canonical)
            if not img_full_path:
                try:
                    paper_data = load_json()
                    paper_id = str(paper_data.get("paper_id") or paper_data.get("id") or "").strip()
                    if not paper_id and isinstance(paper_data.get("paper_data"), dict):
                        paper_id = str(paper_data["paper_data"].get("paper_id", "")).strip()
                    if paper_id:
                        backend_root = _os.path.join(str(_os.path.dirname(_os.path.abspath(__file__))), "..", "..")
                        user_dir = _os.path.join(backend_root, "user")

                        # Priority 1: user/<paper_id>/image/ (canonical — storage fix 2026-07-04)
                        canonical_img_dir = _os.path.join(user_dir, paper_id, "image")
                        if _os.path.isdir(canonical_img_dir):
                            for name in (image_path, image_path_norm):
                                candidate = _os.path.join(canonical_img_dir, name)
                                if _os.path.isfile(candidate):
                                    img_full_path = candidate
                                    break

                        # Priority 2: user/<username>/<paper_id>/image/ (legacy)
                        if not img_full_path:
                            for username in _os.listdir(user_dir):
                                dd = _os.path.join(user_dir, username, paper_id, "image")
                                if _os.path.isdir(dd):
                                    for name in (image_path, image_path_norm):
                                        candidate = _os.path.join(dd, name)
                                        if _os.path.isfile(candidate):
                                            img_full_path = candidate
                                            break
                                if img_full_path:
                                    break
                except Exception:
                    pass
            
            if not img_full_path:
                img_full_path = image_path  # fallback
    from docx.shared import Inches, Cm, Emu
    from docx.oxml.ns import qn as qn_fig
    
    # Max image width: 50% of column width, regardless of layout
    if CFG["columns"] > 1:
        max_width_cm = CFG.get("col_width_cm", 8.0) * 0.50
    else:
        max_width_cm = CFG.get("page_width_cm", 16.0) * 0.50
    
    img_to_embed = ""
    if img_full_path and _os.path.isfile(img_full_path):
        img_to_embed = img_full_path
    elif image_path and _os.path.isfile(image_path):
        img_to_embed = image_path
    elif image_url:
        # Download to temp file
        import tempfile, urllib.request
        try:
            fd, tmp = tempfile.mkstemp(suffix=".png")
            _os.close(fd)
            urllib.request.urlretrieve(image_url, tmp)
            if _os.path.getsize(tmp) > 100:
                img_to_embed = tmp
        except Exception:
            pass
    
    if img_to_embed:
        try:
            # Add image paragraph (centered)
            p_img = doc.add_paragraph()
            p_img.alignment = WD_ALIGN_PARAGRAPH.CENTER
            set_para_spacing(p_img, before_pt=14, after_pt=8, line_tw=240)
            
            # Get image dimensions
            from PIL import Image as PILImage
            with PILImage.open(img_to_embed) as im:
                img_w, img_h = im.size
            
            # Calculate display size
            max_width_emu = int(Cm(max_width_cm))
            if img_w > 0:
                scale = max_width_emu / img_w
                display_width = max_width_emu
                display_height = int(img_h * scale)
            else:
                display_width = max_width_emu
                display_height = max_width_emu
            
            run_img = p_img.add_run()
            run_img.add_picture(img_to_embed, width=display_width, height=display_height)
            image_embedded = True
            
            # Cleanup temp file if downloaded
            if img_to_embed.startswith(_os.path.join(tempfile.gettempdir(), '')):
                try:
                    _os.unlink(img_to_embed)
                except Exception:
                    pass
        except Exception as e:
            # Fall through to placeholder
            pass

    # AI prompt placeholder (only if no image embedded)
    if not image_embedded:
        p_img = doc.add_paragraph()
        p_img.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_para_spacing(p_img, before_pt=14, after_pt=8, line_tw=240)  # Sama dengan gambar embedded
        dyn_prompt = prompt_hint or (
            f"Buatkan gambar/diagram/ilustrasi teknis yang merepresentasikan "
            f"'{title}'. Pastikan visualnya profesional dan cocok untuk jurnal akademik."
        )
        prompt_text = f"[PROMPT UNTUK AI GAMBAR: {title}. {dyn_prompt}]"
        run = p_img.add_run(prompt_text)
        set_run_font(run, CFG["font_body"], CFG["size_body"], italic=True, color=(0xFF, 0x00, 0x00))

    # Caption (always shown — outside the if-block)
    p_cap = doc.add_paragraph()
    p_cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    set_para_spacing(p_cap, before_pt=3, after_pt=0, line_tw=240)
    # Detect if title already has "Gambar N" or "Figure N" prefix
    caption_prefix_re = re.compile(r'^(Gambar|Figure|Fig\.)\s+\d+[\.:]?\s*', re.IGNORECASE)
    m = caption_prefix_re.match(title)
    if m:
        # 2 runs: [label] bold + [description] normal — matches template pattern
        label_text = m.group(0).rstrip()
        desc_text = title[m.end():].lstrip()
        run_label = p_cap.add_run(label_text + " ")
        set_run_font(run_label, CFG["font_body"], CFG["size_caption"], bold=True)
        if desc_text:
            run_desc = p_cap.add_run(desc_text)
            set_run_font(run_desc, CFG["font_body"], CFG["size_caption"])
    else:
        # No prefix — use CFG fig_prefix: 2 runs [label bold] + [desc normal]
        run_label = p_cap.add_run(f"{CFG['fig_prefix']} {fig_no}. ")
        set_run_font(run_label, CFG["font_body"], CFG["size_caption"], bold=True)
        run_title = p_cap.add_run(title)
        set_run_font(run_title, CFG["font_body"], CFG["size_caption"])


def add_table_element(doc, tbl_data, tbl_counter, borders=None):
    """Add table from data with border style matching template."""
    tbl_no = str(tbl_data.get("TableNumber", tbl_counter)).strip()
    title = str(tbl_data.get("Title", f"Table {tbl_no}")).strip()
    headers = tbl_data.get("Headers", [])
    rows = tbl_data.get("Rows", [])

    # Title above table
    p_title = doc.add_paragraph()
    p_title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    set_para_spacing(p_title, before_pt=3, after_pt=0, line_tw=240)
    # Detect if title already has "Table N" or "Tabel N" prefix
    caption_prefix_re = re.compile(r'^(Tabel|Table)\s+\d+[\.:]?\s*', re.IGNORECASE)
    m = caption_prefix_re.match(title)
    if m:
        label_text = m.group(0)
        desc_text = title[m.end():].lstrip()
        run_label = p_title.add_run(label_text)
        set_run_font(run_label, CFG["font_body"], CFG["size_caption"], bold=True)
        if desc_text:
            run_title = p_title.add_run(" " + desc_text)
            set_run_font(run_title, CFG["font_body"], CFG["size_caption"])
    else:
        run_label = p_title.add_run(f"{CFG['tbl_prefix']} {tbl_no}. ")
        set_run_font(run_label, CFG["font_body"], CFG["size_caption"], bold=True)
        run_title = p_title.add_run(title)
        set_run_font(run_title, CFG["font_body"], CFG["size_caption"])

    if not headers and not rows:
        if CFG["columns"] > 1:
            insert_column_break(doc, CFG["columns"])
        return

    n_cols = len(headers) if headers else (len(rows[0]) if rows else 2)
    n_rows = len(rows) + (1 if headers else 0)
    table = doc.add_table(rows=n_rows, cols=n_cols)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    set_table_borders(table, borders if borders is not None else CFG["table_borders"])

    # Header row
    if headers:
        for j, h in enumerate(headers):
            if j < n_cols:
                cell = table.rows[0].cells[j]
                cell.text = ""
                p = cell.paragraphs[0]
                set_para_spacing(p, before_pt=0, after_pt=0, line_tw=240)
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                run = p.add_run(_clean_latex(str(h)))
                set_run_font(run, CFG["font_body"], CFG["size_caption"], bold=True)

    # Data rows
    start_row = 1 if headers else 0
    for i, row_data in enumerate(rows):
        if not isinstance(row_data, list):
            continue
        row_idx = start_row + i
        if row_idx >= n_rows:
            break
        for j, val in enumerate(row_data):
            if j < n_cols:
                cell = table.rows[row_idx].cells[j]
                cell.text = ""
                p = cell.paragraphs[0]
                set_para_spacing(p, before_pt=0, after_pt=0, line_tw=240)
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                run = p.add_run(_clean_latex(str(val)))
                set_run_font(run, CFG["font_body"], CFG["size_caption"])

    # Spacer after table to prevent next content from crowding
    if rows:
        p_spacer = doc.add_paragraph()
        set_para_spacing(p_spacer, before_pt=3, after_pt=8)


def add_formula(doc, formula_data):
    latex = str(formula_data.get("latex", formula_data.get("Formula", ""))).strip()
    number = str(formula_data.get("FormulaNumber", "")).strip()
    if not latex:
        return
    
    import re
    from lxml import etree
    from latex2mathml.converter import convert as latex2mathml
    from mathml2omml import convert as mathml2omml
    from docx.oxml.ns import qn
    
    try:
        # 1. Kalkulasi Lebar Kolom & Paksa Resize Skala Matriks
        col_w_cm = 7.5 if CFG.get("columns", 2) >= 2 else 16.0
        max_fw_cm = col_w_cm * 0.90
        
        cleaned = re.sub(r'\\[a-zA-Z]+|\{|\}|\[|\]|\^|\_|\$|\\', '', latex)
        formula_size = CFG["size_body"]
        
        is_matrix = "matrix" in latex or "cases" in latex or "\\\\" in latex
        if is_matrix:
            formula_size = max(5.0, formula_size - 2.5) 
        else:
            est_cm = len(cleaned) * formula_size * 0.38 / 28.35
            if est_cm > max_fw_cm:
                scale = max_fw_cm / est_cm
                formula_size = max(5.0, formula_size * scale)
                
        effective_halfpt = int(formula_size * 2)

        # 2. Konversi ke OMML sebagai Inline Math (BUKAN oMathPara)
        mathml_str = latex2mathml(latex)
        omml_str = mathml2omml(mathml_str)
        
        MATH_NS = "http://schemas.openxmlformats.org/officeDocument/2006/math"
        
        omml_inner = omml_str.replace(f'<m:oMath xmlns:m="{MATH_NS}">', '').replace('</m:oMath>', '')
        if omml_inner.startswith('<m:oMath>'):
            omml_inner = omml_inner.replace('<m:oMath>', '', 1)
            
        omml_wrapped = f'<m:oMath xmlns:m="{MATH_NS}">{omml_inner}</m:oMath>'
        oMath = etree.fromstring(omml_wrapped)
        
        # 3. Injeksi Properties OpenXML Legal (Harus di insert di INDEX 0)
        for omath_run in oMath.iter(f'{{{MATH_NS}}}r'):
            wrPr = omath_run.find(qn('w:rPr'))
            if wrPr is None:
                wrPr = etree.Element(qn('w:rPr'))
                omath_run.insert(0, wrPr)  # INI WAJIB INSERT(0), JANGAN SUBELEMENT
            
            rFonts = wrPr.find(qn('w:rFonts'))
            if rFonts is None:
                rFonts = etree.SubElement(wrPr, qn('w:rFonts'))
            rFonts.set(qn('w:ascii'), 'Cambria Math')
            rFonts.set(qn('w:hAnsi'), 'Cambria Math')
            
            sz = wrPr.find(qn('w:sz'))
            if sz is None:
                sz = etree.SubElement(wrPr, qn('w:sz'))
            sz.set(qn('w:val'), str(effective_halfpt))
            
            szCs = wrPr.find(qn('w:szCs'))
            if szCs is None:
                szCs = etree.SubElement(wrPr, qn('w:szCs'))
            szCs.set(qn('w:val'), str(effective_halfpt))

        # 4. Bangun Paragraf & Setup TABS (Agar bisa sejajar)
        body = doc._element.body
        final_sectpr = body.find(qn("w:sectPr"))
        
        p_elem = etree.Element(qn("w:p"))
        pPr = etree.SubElement(p_elem, qn("w:pPr"))
        
        jc = etree.SubElement(pPr, qn("w:jc"))
        jc.set(qn("w:val"), "left")
        
        spacing = etree.SubElement(pPr, qn("w:spacing"))
        spacing.set(qn("w:before"), "120")
        spacing.set(qn("w:after"), "120")
        spacing.set(qn("w:line"), "240")
        spacing.set(qn("w:lineRule"), "auto")
        
        center_twips = int((col_w_cm * 28.346 * 20) / 2)
        right_twips = int(col_w_cm * 28.346 * 20)
        
        tabs = etree.SubElement(pPr, qn("w:tabs"))
        tab_center = etree.SubElement(tabs, qn("w:tab"))
        tab_center.set(qn("w:val"), "center")
        tab_center.set(qn("w:pos"), str(center_twips))
        
        tab_right = etree.SubElement(tabs, qn("w:tab"))
        tab_right.set(qn("w:val"), "right")
        tab_right.set(qn("w:pos"), str(right_twips))

        # 5. Eksekusi Struktur Paragraf: [Tab Center] -> Formula -> [Tab Right] -> Number
        run_tab1 = etree.SubElement(p_elem, qn("w:r"))
        etree.SubElement(run_tab1, qn("w:tab"))
        
        p_elem.append(oMath)
        
        if number:
            run_num = etree.SubElement(p_elem, qn("w:r"))
            etree.SubElement(run_num, qn("w:tab"))
            
            rPr_num = etree.SubElement(run_num, qn("w:rPr"))
            rFonts_num = etree.SubElement(rPr_num, qn("w:rFonts"))
            rFonts_num.set(qn("w:ascii"), CFG["font_body"])
            
            sz_num = etree.SubElement(rPr_num, qn("w:sz"))
            sz_num.set(qn("w:val"), str(CFG["size_body"] * 2))
            
            t_num = etree.SubElement(run_num, qn("w:t"))
            t_num.text = f"({number})"
            t_num.set(qn("xml:space"), "preserve")
        
        # 6. Finalisasi Paragraf
        if final_sectpr is not None:
            final_sectpr.addprevious(p_elem)
        else:
            body.append(p_elem)
            
    except Exception as e:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_para_spacing(p, before_pt=6, after_pt=6)
        display = f"{latex}    ({number})" if number else latex
        run = p.add_run(display)
        set_run_font(run, CFG["font_body"], CFG["size_body"], bold=True, color=CFG["heading_color"])


def add_references(doc, data):
    refs_data = data.get("references", {})
    if isinstance(refs_data, dict):
        refs_list = refs_data.get("content") or refs_data.get("items") or []
    elif isinstance(refs_data, list):
        refs_list = refs_data
    else:
        refs_list = []

    if not refs_list:
        return

    # Heading
    add_section_heading(doc, "References")

    # Items
    for i, ref in enumerate(refs_list, 1):
        ref_text = _format_reference(ref)
        if not ref_text:
            continue
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        set_para_spacing(p, before_pt=0, after_pt=0)
        set_para_indent(p, left_tw=360, hanging_tw=360)
        # Only add [N] prefix if text doesn't already have one
        if re.match(r'^\s*\[\d+\]', ref_text):
            run = p.add_run(ref_text)
        else:
            run = p.add_run(f"[{i}] {ref_text}")
        set_run_font(run, CFG["font_body"], CFG["size_reference"])


def process_content_items(doc, content_list, fig_counter, tbl_counter, table_borders=None):
    """Process a list of content items (text, gambar, rumus, tabel)."""
    if not isinstance(content_list, list):
        return fig_counter, tbl_counter

    for item in content_list:
        if not isinstance(item, dict):
            continue
        kind = str(item.get("id", "")).lower()

        if kind in ("text", "paragraf", "paragraph"):
            text = str(item.get("text", item.get("Text", ""))).strip()
            if text:
                add_body_text(doc, text)

        elif kind in ("gambar", "image", "figure"):
            fig_counter += 1
            add_figure(doc, item, fig_counter)

        elif kind in ("tabel", "table"):
            tbl_counter += 1
            add_table_element(doc, item, tbl_counter, borders=table_borders)

        elif kind in ("rumus", "equation", "formula", "persamaan"):
            add_formula(doc, item)

    return fig_counter, tbl_counter


def process_section(doc, section_data, fig_counter, tbl_counter, table_borders=None):
    """Process a section (and its subsections) recursively."""
    if not isinstance(section_data, dict):
        return fig_counter, tbl_counter

    # Section title
    title = str(section_data.get("title", section_data.get("Title", ""))).strip()
    if title:
        add_section_heading(doc, title)

    # Content items at this level
    content = section_data.get("content", section_data.get("Content", []))
    fig_counter, tbl_counter = process_content_items(doc, content, fig_counter, tbl_counter, table_borders=table_borders)

    # Find subsections (keys like section2a, section2b, etc.)
    for key in sorted(section_data.keys()):
        if key in ("title", "Title", "content", "Content", "id"):
            continue
        val = section_data[key]
        if isinstance(val, dict) and ("title" in val or "Title" in val or "content" in val or "Content" in val):
            # This is a subsection
            sub_title = str(val.get("title", val.get("Title", ""))).strip()
            if sub_title:
                add_subsection_heading(doc, sub_title)
            sub_content = val.get("content", val.get("Content", []))
            fig_counter, tbl_counter = process_content_items(doc, sub_content, fig_counter, tbl_counter, table_borders=table_borders)

            # Check for sub-subsections
            for subkey in sorted(val.keys()):
                if subkey in ("title", "Title", "content", "Content", "id"):
                    continue
                subval = val[subkey]
                if isinstance(subval, dict) and ("title" in subval or "Title" in subval or "content" in subval or "Content" in subval):
                    ssub_title = str(subval.get("title", subval.get("Title", ""))).strip()
                    if ssub_title:
                        add_subsection_heading(doc, ssub_title)
                    ssub_content = subval.get("content", subval.get("Content", []))
                    fig_counter, tbl_counter = process_content_items(doc, ssub_content, fig_counter, tbl_counter, table_borders=table_borders)

    return fig_counter, tbl_counter


def _measure_section_weights(doc):
    """Hitung jumlah elemen konten (paragraf non-sectPr + tabel) di tiap segmen
    antara inline sectPr-paragraph berurutan. Dipakai untuk distribusi body
    PROPORSIONAL supaya layout multi-kolom AEJ (body 2-kolom + referensi
    1-kolom) terjaga. Diukur SEBELUM clear_body (doc masih berisi original).

    Return list selaras dengan boundaries = sectpr_paras[1:] + final body sectPr:
    elemen ke-i = jumlah konten di section yang berakhir pada boundary ke-i.
    """
    body = doc._element.body
    seg_counts = []
    current = 0
    seen_first = False
    for child in body.iterchildren():
        if child.tag == qn("w:sectPr"):
            continue  # final body sectPr (level body), lewati
        if child.tag == qn("w:p"):
            pPr = child.find(qn("w:pPr"))
            if pPr is not None and pPr.find(qn("w:sectPr")) is not None:
                # Boundary tercapai: tutup segmen berjalan.
                seg_counts.append(current)
                current = 0
                seen_first = True
                continue
        # Elemen konten (paragraf tanpa sectPr, atau tabel).
        if seen_first:
            current += 1
    seg_counts.append(current)  # segmen ekor (konten setelah sectPr-para terakhir)
    # seg_counts[0] = area judul (sebelum sectPr-para pertama) -> dibuang.
    return seg_counts[1:] if len(seg_counts) > 1 else []


